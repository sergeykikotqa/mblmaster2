import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { pathToFileURL } from 'node:url';

const root = process.cwd();
const sourcePath = path.join(root, 'config', 'redirects.rules');
const outputs = {
  transitional: path.join(root, '_redirects'),
  hostMap: path.join(root, 'nginx', 'generated', 'redirect-host-map.conf'),
  paths: path.join(root, 'nginx', 'generated', 'redirect-paths.conf'),
  publicOrigin: path.join(root, 'nginx', 'generated', 'public-origin.conf'),
  robots: path.join(root, 'public', 'robots.txt'),
};
const validStatuses = new Set([301, 307, 404, 410]);
const canonicalOrigin = new URL(String(process.env.PUBLIC_SITE_URL || 'https://example.com').trim()).origin;
const CANONICAL_ORIGIN_TOKEN = '__CANONICAL_ORIGIN__';

function fail(message) {
  throw new Error(`[redirect-generator] ${message}`);
}

function parsePolicy(content) {
  const entries = [];
  const seenSources = new Set();

  for (const [index, rawLine] of content.split(/\r?\n/).entries()) {
    const lineNumber = index + 1;
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) {
      entries.push({ type: 'comment', value: rawLine.trimEnd() });
      continue;
    }

    const parts = line.split(/\s+/);
    if (parts.length !== 3) fail(`line ${lineNumber} must contain source, target and status`);
    const [source, target, rawStatus] = parts;
    const status = Number(rawStatus);
    if (!validStatuses.has(status)) fail(`line ${lineNumber} has unsupported status ${rawStatus}`);
    if (seenSources.has(source)) fail(`line ${lineNumber} duplicates source ${source}`);
    seenSources.add(source);

    const isAbsolute = /^https?:\/\//.test(source);
    if (!isAbsolute && !source.startsWith('/')) fail(`line ${lineNumber} source must be an HTTP URL or path`);
    if (!/^https?:\/\//.test(target) && !target.startsWith('/') && !target.startsWith(CANONICAL_ORIGIN_TOKEN)) {
      fail(`line ${lineNumber} target must be an HTTP URL or path`);
    }
    if (/[^A-Za-z0-9_./:*-]/.test(source) || /[^A-Za-z0-9_./:*-]/.test(target)) {
      fail(`line ${lineNumber} contains characters outside the redirect grammar`);
    }

    entries.push({ type: 'rule', source, target, status, isAbsolute });
  }

  return entries;
}

function resolveTarget(target) {
  return target.replace(CANONICAL_ORIGIN_TOKEN, canonicalOrigin);
}

function renderTransitional(entries) {
  const lines = [
    '# AUTO-GENERATED by scripts/generate-runtime-redirects.mjs',
    '# Authority: config/redirects.rules. Do not edit this artifact directly.',
  ];
  for (const entry of entries) {
    if (entry.type === 'comment') {
      lines.push(entry.value);
      continue;
    }
    const force = entry.status === 301 || entry.status === 307 ? '!' : '';
    lines.push(`${entry.source} ${resolveTarget(entry.target)} ${entry.status}${force}`);
  }
  return `${lines
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim()}\n`;
}

function escapeRegex(value) {
  return value.replace(/[.+?^${}()|[\]\\]/g, '\\$&');
}

function pathPatternToRegex(source) {
  const segments = source.split('/').slice(1);
  const rendered = segments.map((segment) => {
    if (segment === '*') return '.*';
    if (segment.startsWith(':')) return '[^/]+';
    return escapeRegex(segment);
  });
  return `/${rendered.join('/')}`;
}

function renderReturn(rule) {
  const target = resolveTarget(rule.target);
  if (rule.status === 404 || rule.status === 410) return `return ${rule.status};`;
  if (/^https?:\/\//.test(target)) return `return ${rule.status} ${target};`;
  return `return ${rule.status} ${target}$is_args$args;`;
}

function renderPathRedirects(entries) {
  const lines = [
    '# AUTO-GENERATED by scripts/generate-runtime-redirects.mjs',
    '# Authority: config/redirects.rules. Included inside the public server.',
  ];

  for (const entry of entries) {
    if (entry.type === 'comment') continue;
    if (entry.isAbsolute) continue;

    const action = renderReturn(entry);
    const locationPreamble = entry.source.startsWith('/api/')
      ? 'include /etc/nginx/security-headers.conf; add_header Cache-Control "no-store" always; '
      : '';
    const hasNamedSegment = /:[A-Za-z0-9_-]+/.test(entry.source);
    const suffixWildcard = entry.source.endsWith('/*');
    if (!hasNamedSegment && suffixWildcard) {
      const prefix = entry.source.slice(0, -1);
      lines.push(`location ^~ ${prefix} { ${locationPreamble}${action} }`);
    } else if (!hasNamedSegment && !entry.source.includes('*')) {
      lines.push(`location = ${entry.source} { ${locationPreamble}${action} }`);
    } else {
      lines.push(`location ~ ^${pathPatternToRegex(entry.source)}$ { ${locationPreamble}${action} }`);
    }
  }

  return `${lines.join('\n')}\n`;
}

function renderHostMap(entries) {
  const origins = new Set();
  for (const entry of entries) {
    if (entry.type === 'comment' || !entry.isAbsolute) continue;
    const source = new URL(entry.source.replace('*', '__mbl_splat__'));
    if (
      source.pathname !== '/__mbl_splat__' ||
      entry.target !== `${CANONICAL_ORIGIN_TOKEN}/:splat` ||
      entry.status !== 301
    ) {
      fail(
        `host rule ${entry.source} must redirect its complete path to ${CANONICAL_ORIGIN_TOKEN}/:splat with 301`
      );
    }
    origins.add(`${source.protocol.slice(0, -1)}:${source.hostname}`);
  }

  const lines = [
    '# AUTO-GENERATED by scripts/generate-runtime-redirects.mjs',
    '# Authority: config/redirects.rules. Included in the http context.',
    'map "$scheme:$host" $mbl_canonical_redirect_origin {',
    '    default 0;',
  ];
  for (const origin of [...origins].sort()) lines.push(`    "${origin}" 1;`);
  lines.push('}');
  return `${lines.join('\n')}\n`;
}

function renderPublicOrigin() {
  const hostname = new URL(canonicalOrigin).hostname;
  return `# AUTO-GENERATED by scripts/generate-runtime-redirects.mjs
# PUBLIC_SITE_URL is the only canonical-origin input.
map "" $mbl_public_origin {
    default "${canonicalOrigin}";
}
map $host $mbl_public_host_allowed {
    default 0;
    "${hostname}" 1;
    "127.0.0.1" 1;
    "localhost" 1;
}
`;
}

function renderRobots() {
  return `User-agent: *
Disallow: /admin/
Disallow: /api/
Disallow: /decapcms/

Clean-param: utm_source&utm_medium&utm_campaign&utm_term&utm_content /
Clean-param: tag /

Sitemap: ${canonicalOrigin}/sitemap-index.xml
`;
}

function compareOrWrite(filePath, expected, checkOnly) {
  if (checkOnly) {
    if (!fs.existsSync(filePath) || fs.readFileSync(filePath, 'utf8') !== expected) {
      fail(`${path.relative(root, filePath)} is stale; run node scripts/generate-runtime-redirects.mjs`);
    }
    return;
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, expected, 'utf8');
}

function main() {
  if (!fs.existsSync(sourcePath)) fail('missing config/redirects.rules');
  const entries = parsePolicy(fs.readFileSync(sourcePath, 'utf8'));
  const checkOnly = process.argv.includes('--check');
  compareOrWrite(outputs.transitional, renderTransitional(entries), checkOnly);
  compareOrWrite(outputs.hostMap, renderHostMap(entries), checkOnly);
  compareOrWrite(outputs.paths, renderPathRedirects(entries), checkOnly);
  compareOrWrite(outputs.publicOrigin, renderPublicOrigin(), checkOnly);
  compareOrWrite(outputs.robots, renderRobots(), checkOnly);
  console.log(`[redirect-generator] ${checkOnly ? 'verified' : 'generated'} ${Object.keys(outputs).length} artifacts`);
}

const isDirectRun = process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;
if (isDirectRun) main();

export { parsePolicy, renderHostMap, renderPublicOrigin, renderRobots, renderTransitional };
